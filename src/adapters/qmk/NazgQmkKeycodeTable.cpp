// Every fixed QMK keycode, from before the renumbering to keycode spec 0.0.9. DATA ONLY --
// the code that reads it is in NazgQmkKeycodes.cpp.
//
// Produced from QMK's merged keycode JSON (keyboards.qmk.fm/v1/constants/keycodes_<ver>.json)
// for 0.0.1 onwards, and for the two pre-renumbering versions from the keycodes VIA pinned
// with static asserts (quantum/via_ensure_keycode.h, last revision before #18643) plus VIA's
// own keycodes (quantum/via.h). Committed as plain source: there is deliberately no
// generator in the repo. When QMK adds a keycode version, regenerate by hand following the
// procedure in docs/research_material/keycodes.md, and review the diff like any other change.
//
// One row per (keycode, value) span. A keycode that never moved is one row; one whose
// value changed has a row per value, each with its own [since, removedIn) versions and
// the same name. Rows are sorted by value, then by version. KC_A is one row from Legacy
// on: basic keycodes kept their values through the renumbering.
//
// 1064 rows. Columns: value, since, removedIn, name, group, label.
//   name  - the short name QMK keymaps use (KC_ENT, UG_TOGG), from the newest version.
//           It is also the keycode's identity: it survives QMK renames, so the 0.0.1
//           RGB_TOG row and the 0.0.9 value are both "UG_TOGG", and the pre-renumbering
//           RESET is "QK_BOOT".
//   label - QMK's display label, made ASCII (C#0 for C-sharp-subscript-0, <-> for the
//           swap arrow); empty where QMK gives none, which is mostly steno. A label with
//           a backslash is a raw literal, so the backslash key reads R"(\)" here.

